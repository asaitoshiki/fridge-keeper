/** 冷蔵・野菜室・常温・冷凍の略号と、収納の種類の対応 */
const SHELF_KEYS = { FRIDGE: 'F', VEGETABLE_DRAWER: 'V', ROOM_TEMP: 'R', FREEZER: 'Z' };
const SHELF_KIND_OF = { F: 'FRIDGE', V: 'VEGETABLE_DRAWER', R: 'ROOM_TEMP', Z: 'FREEZER' };

/* --- 名前から食品を引く --------------------------------------------------- */

/** カタカナをひらがなに寄せる。「ジャガイモ」と「じゃがいも」を同じものとして引くため */
function toHiragana(text) {
  return text.replace(/[ァ-ヶ]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0x60));
}

/**
 * 名前の引き方を一度だけ作る。見本帳の名前と読みの両方をひらがなに寄せて持つ。
 * 長い名前から順に当てるので、「鶏もも肉」が「もも」より先に当たる。
 */
let shelfIndex = null;
function shelfLifeIndex() {
  if (shelfIndex) return shelfIndex;
  const entries = [];
  Object.keys(SHELF_LIFE).forEach((name) => {
    const preset = typeof FOOD_BY_NAME !== 'undefined' ? FOOD_BY_NAME[name] : null;
    const category = preset ? preset.category : null;
    const keys = new Set([toHiragana(name), toHiragana(name.replace(/（.*?）/g, ''))]);
    if (preset && preset.kana) keys.add(preset.kana);
    keys.forEach((key) => {
      if (key) entries.push({ key, name, category });
    });
  });
  entries.sort((a, b) => b.key.length - a.key.length);
  shelfIndex = entries;
  return entries;
}

/**
 * 食材の名前に当たる食品の目安。当たらなければ null。
 *
 * 名前がそのまま一致すればそれを使う。そうでなければ、名前に含まれる食品名を探す
 * （「新じゃがいも」→ じゃがいも、「ジャガイモ」→ じゃがいも）。
 * 含まれるだけの当て方は外れることがあるので、カテゴリが同じときだけ採る。
 * 「鶏もも」が果物の「もも」に化けないようにするため。
 * 略した名前（「鶏もも」→ 鶏もも肉）は、食品名の頭と一致すれば採る。
 * 1文字の食品名（水・塩・卵）は、名前の終わりに付くときだけ採る（天然水・岩塩・ゆで卵）。
 * 「水菜」が水にならないようにするため。
 */
function shelfLifeFor(name, category) {
  if (!name) return null;
  if (SHELF_LIFE[name]) return { name, ...SHELF_LIFE[name] };

  const target = toHiragana(name.trim());
  const index = shelfLifeIndex();
  const exact = index.find((e) => e.key === target);
  if (exact) return { name: exact.name, ...SHELF_LIFE[exact.name] };

  const sameCategory = (e) => !category || !e.category || e.category === category;
  const hit = index.find((e) => e.key.length >= 2 && target.includes(e.key) && sameCategory(e))
    || index.find((e) => target.length >= 2 && e.key.startsWith(target) && sameCategory(e))
    || index.find((e) => e.key.length === 1 && target.endsWith(e.key) && sameCategory(e));
  return hit ? { name: hit.name, ...SHELF_LIFE[hit.name] } : null;
}
